#!/usr/bin/env python3
"""Build a named style variant of a reel (styles.json).

    python3 scripts/make_style.py <base> <minimal|hype>

Writes src/methodology/reels/<base>-<style>.config.ts from the base reel's config (same cut,
words, grade, music, post, claims) reshaped to the style, registers it in Root.tsx, and for
hype marks key words and zoom punches (scripts/dynamic_keys.py). Then run the preview steps
and get the scene map approved before rendering. An existing variant is never overwritten
without --force (it may hold approved edits).
"""
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import reel_config  # noqa: E402


def main():
    a = [x for x in sys.argv[1:] if not x.startswith('--')]
    if len(a) != 2:
        sys.exit(__doc__)
    base, style = a
    styles = json.load(open(os.path.join(ROOT, 'styles.json')))['styles']
    if style not in styles or style == 'studio':
        sys.exit('make_style: style must be one of %s (studio is the base build itself)' % ', '.join(k for k in styles if k != 'studio'))
    vid = '%s-%s' % (base, style)
    bc = reel_config.load(base)
    beds = json.load(open(os.path.join(ROOT, 'sounds.json'))).get('music_beds') or []
    if (bc.get('music') or beds) and bc.get('musicStart') is None:
        # the house bed has a quiet 10s intro: without musicStart the music takes 11s to arrive
        # (caught twice, Chris 2026-10-02). Set it on the BASE so every variant inherits it.
        print('make_style: WARNING %s has no "musicStart" (the bed will take ~11s to come in). '
              'Add "musicStart": 11 to the base config first, then re-run.' % base)
    out = reel_config.config_path(vid)
    if os.path.exists(out) and '--force' not in sys.argv:
        sys.exit('make_style: %s exists (use --force to rebuild it from %s)' % (os.path.relpath(out, ROOT), base))
    s = open(reel_config.config_path(base)).read()
    s = s.replace('"id": "%s"' % base, '"id": "%s"' % vid, 1)
    s = re.sub(r'  "scenes": \[.*?\n  \],', '  "scenes": [\n    {"from": 0, "mode": "full"}  // %s style: full screen throughout\n  ],' % style, s, flags=re.S)
    s = re.sub(r'  "swaps": \[.*?\n  \],', '  "swaps": [\n  ],', s, flags=re.S)
    s = re.sub(r'  "thumbnail": [^\n]*\n', '', s)
    s = re.sub(r'  "zooms": \[.*?\n  \],\n', '', s, flags=re.S)
    s = re.sub(r'  "captionAccent": [^\n]*\n', '', s)
    s = re.sub(r'  "captionStyle": "[a-z]+",[^\n]*\n', '', s)
    if style == 'minimal':
        s = re.sub(r'  "backText": \[.*?\n  \],\n', '', s, flags=re.S)
        s = re.sub(r'  "inserts": \[.*?\n  \],\n', '', s, flags=re.S)
        # Minimal is captions only: of the effects it keeps the camera transitions (moves, not overlays)
        m = re.search(r'  "effects": \[\n(.*?)\n  \],\n', s, flags=re.S)
        if m:
            keep = [ln for ln in m.group(1).split('\n') if '"transition"' in ln and re.search(r'"style": "(whip|zoom|spin)"', ln)]
            keep = [ln.rstrip().rstrip(',') for ln in keep]
            body = ('  "effects": [\n' + ',\n'.join(keep) + '\n  ],\n') if keep else ''
            s = s[:m.start()] + body + s[m.end():]
        s = re.sub(r'  "cover": [^\n]*\n', '  "cover": null,  // minimal style: no overlays outside captions\n', s)
        cap = '  "captionStyle": "punch",  // minimal style\n'
    else:
        cap = ('  "captionStyle": "dynamic",  // hype style: two-font stacked captions\n  "captionAccent": "playfair",\n'
               '  "zooms": [  // generated by scripts/dynamic_keys.py\n  ],\n')
    s = s.replace('  "placement":', cap + '  "placement":', 1)
    open(out, 'w').write(s)
    root = os.path.join(ROOT, 'src', 'methodology', 'Root.tsx')
    r = open(root).read()
    line = "    <Reel id=\"%s\" load={() => import('./reels/%s.config')} />" % (vid, vid)
    if line not in r:
        r = r.replace('    <Reel id="%s" load' % base, line + '\n    <Reel id="%s" load' % base, 1)
        open(root, 'w').write(r)
    if style == 'hype':
        subprocess.run([sys.executable, os.path.join(HERE, 'dynamic_keys.py'), vid], check=True)
    print('make_style: wrote %s and registered it. Next: matte_reel.py, scene_map.py, test_layout.mjs, extract_reel_stills.py --preview, then approval.'
          % os.path.relpath(out, ROOT))


if __name__ == '__main__':
    main()
